//! Скан реестров слоя работы: направления, срезы, единицы работы.
//!
//! Устроен как скан решений: один документ — один файл с каноническим
//! именем, константа-ссылка на каждый, сверка идентификатора с компилятором.
//! Сверх того порождается правило, связывающее две записи: радиус работы не
//! выше потолка её среза. Оно вычисляется в `const`, поэтому нарушение —
//! ошибка компиляции, а не находка валидатора.

use crate::{ScanError, ScannedSlug};
use dacc_core::anchor_rules::slug_ident;
use std::{fmt::Write as _, path::Path};

/// Вид реестра слоя работы и имена того, что для него порождается.
pub struct PlanKind {
    macro_name: &'static str,
    module: &'static str,
    reference: &'static str,
    record: &'static str,
    item: &'static str,
    all: &'static str,
    /// Запись вида в документации порождённого кода: «Slice 3».
    noun: &'static str,
    /// Он же строчной буквой: «Reference to slice 3». Падежей у английского
    /// нет, но регистр в середине фразы другой, поэтому форма отдельная.
    lower: &'static str,
    /// Множественное число: «References to slices».
    plural: &'static str,
}

/// Реестр направлений.
pub const THRUSTS: PlanKind = PlanKind {
    macro_name: "thrust",
    module: "thrust",
    reference: "ThrustRef",
    record: "Thrust",
    item: "THRUST",
    all: "ALL_THRUSTS",
    noun: "Thrust",
    lower: "thrust",
    plural: "thrusts",
};

