//! Слой доступа: экспорт скомпилированного реестра в машинный (JSON) и
//! контекстный (XML) форматы (решение 21, спецификация RFC-0003).
//!
//! Проекция порождается скомпилированным реестром, а не повторным разбором
//! исходников, поэтому разойтись с кодом не может. Проекция не хранит контракт:
//! нормативный текст живёт только в реестре, а сайт, дорожная карта и экспорт —
//! порождённый вид, а не второй носитель. Сериализаторы пишут строку вручную,
//! без внешних зависимостей (решение 14).

pub mod channel;
pub mod json;
pub mod markdown;
pub mod xml;

pub use channel::{publish_channel, ChannelDocuments};
pub use json::export_graph;
pub use markdown::{render_site, Site};
pub use xml::export_slice;
