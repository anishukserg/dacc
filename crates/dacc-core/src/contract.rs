//! Внутренние постусловия чистого кода — уровень контракта с паникой.
//!
//! Граница уровней названа явно: `assure!` проверяет утверждения самого
//! кода — внутренние постусловия и инварианты, — и их нарушение останавливает
//! процесс паникой с контекстом утверждения. Валидация ввода, состояние
//! репозитория и окружения к этому уровню не относятся: там единственный
//! допустимый ответ — `Result` со структурированным отказом, и паника
//! запрещена конвенцией модуля.

/// Постусловие внутренней логики: нарушение останавливает процесс паникой
/// с контекстом утверждения.
///
/// Форма одна: утверждение и необязательный контекст, попадающий в сообщение
/// паники вместе с текстом утверждения и местом вызова.
#[macro_export]
macro_rules! assure {
    ($assertion:expr) => {
        if !$assertion {
            panic!(
                "dacc: internal postcondition violated: {}",
                stringify!($assertion)
            );
        }
    };
    ($assertion:expr, $context:expr) => {
        if !$assertion {
            panic!(
                "dacc: internal postcondition violated: {} — {}",
                $context,
                stringify!($assertion)
            );
        }
    };
}

#[cfg(test)]
mod tests {
    /// Нарушение внутреннего постусловия останавливает процесс паникой с
    /// контекстом — тест фиксирует это как контракт модуля.
    #[test]
    #[should_panic(expected = "internal postcondition violated")]
    fn assure_stops_on_an_internal_violation() {
        crate::assure!(1 + 1 == 3, "сумма не сходится");
    }

    /// Выполненное постусловие не мешает работе.
    #[test]
    fn assure_passes_when_the_postcondition_holds() {
        crate::assure!(1 + 1 == 2);
    }
}
