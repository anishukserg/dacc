use crate::taxonomy::{channel, Subsystem};
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "Фасад — единственная зависимость для разметки реестра",
    status: DocStatus::Active,
    channel: channel::Public,
    subsystems: &[taxon!(Subsystem, Methodology), taxon!(Subsystem, Scan)],
    context: r"
        Фасад dacc реэкспортирует имена, но разметка реестра всё равно требует
        набора крейтов L1. Причин две. Макросы регистрации (adr!, work!, …)
        раскрываются через $crate — крейт-источник, а не фасад, поэтому
        dacc_knowledge::adr! порождает код со ссылкой на dacc_knowledge, и
        потребитель обязан перечислить dacc-knowledge в Cargo.toml.
        Порождённый сканом код ссылается на dacc_core:: и dacc_work:: напрямую.
        Итог: потребитель подключает и dacc, и крейты L1 — фасад снимает налог
        на имена в use, а не на зависимости.
    ",
    decision: r"
        Разметка реестра становится одной зависимостью dacc двумя независимыми
        изменениями.

        Порождённый код: скан параметризует префикс путей и выводит ::dacc::
        вместо dacc_core:: и dacc_work::. Фасад реэкспортирует все имена,
        которые порождает скан, поэтому ссылка резолвится одной зависимостью.
        Это одна правка в эмиттерах скана.

        Макросы: фасад определяет собственные макросы регистрации — тонкие
        обёртки с $crate = dacc, а не реэкспортирует их, потому что $crate
        макроса нельзя перенаправить на реэкспортирующий крейт. Макросы L1
        остаются единственным источником истины внутри реестра DACC; пара
        фасада не может разойтись с ними, потому что тест раскрывает оба
        макроса и сверяет порождённый тип — расхождение ломает сборку.
        Процедурный макрос (переписать регистрацию на атрибуты) отвергнут
        сейчас: он ломает декларативную эргономику и не нужен, пока дублирование
        макросов остаётся одним файлом фасада.
    ",
    trade_offs: &[
        "Плюс: потребитель подключает один крейт dacc вместо набора крейтов L1",
        "Плюс: публичная поверхность одна — и порождённый код, и макросы ведут на фасад",
        "Минус: макросы регистрации определены в двух местах (L1 и фасад), синхронность держит тест",
        "Минус: скан завязывается на имя фасада dacc, а не на крейт L1",
    ],
    constraints: &[
        "Макросы L1 остаются источником истины; фасад не меняет семантику, а лишь переадресует $crate.",
        "Тест сверяет раскрытие макроса фасада с макросом L1 — расхождение ломает сборку.",
        "Порождённый код ссылается на фасад ::dacc::, а не на крейты L1.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 9, 29),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_001, crate::rfc::rfc_2026_002],
);
