dacc_knowledge::adr!(
    title: "CiGate — проверка на пути в основную ветку: независимость вердикта и его потребителя, а не место исполнения",
    status: DocStatus::Active,
    channel: channel::Public,
    subsystems: &[taxon!(Subsystem, Methodology), taxon!(Subsystem, Cli)],
    context: r"
        Калитка (решение 8) исполняется хуками pre-commit и pre-push на машине
        автора. Хук обходится флагом --no-verify, а машина автора — доверие
        автора, а не проекта: её состояние никто, кроме автора, не видит и не
        перепроверяет. Решение 18 перенесло калитку в CI на GitHub Actions, но
        на каждый push в master она исполняется после записи — обнаруживает
        нарушение, а не предотвращает его; предотвращение осталось за защитой
        ветки, которой у DACC пока нет.

        Доказательство готовности (решение 15) уже даёт недостающее свойство:
        вердикт калитки хранится под хэшем дерева без каталога журнала, поэтому
        он контентно-адресуем и перепроверяем с любого дерева, а не привязан к
        машине, которая его вынесла.

        Вопрос работы: что такое проверка на пути в основную ветку — CiGate — и
        чем её вердикт независим от автора, если она исполняется в том числе на
        его машине?

        Рассматривались: считать CiGate только удалённую калитку — тогда
        проверка на закрытии работы без сети не считается; считать CiGate любой
        прогон калитки — тогда хук автора и удалённый CI неразличимы, хотя
        первый обходится флагом; вести две разные сущности — двойная
        терминология без выигрыша.
    ",
    decision: r"
        CiGate — это проверка на пути в основную ветку, чей вердикт и чей
        потребитель независимы от автора. Место исполнения — машина автора или
        удалённый CI — не определяющий признак.

        Независимость вердикта: вердикт контентно-адресуем. Он привязан к хэшу
        дерева без каталога журнала (решение 15) и перепроверяется прогоном
        той же калитки на том же дереве; автор не может подменить вердикт, не
        сменив дерево, а дерево видно всем. Независимость потребителя: вердикт
        потребляет не рабочая копия автора, а журнал — свёртка событий,
        контентно-адресуемая и проверяемая при сборке реестра, — и слияние в
        основную ветку.

        Две известные схемы сверены с этим определением и обе ему отвечают.

        Проверка на закрытии работы без удалённого CI: команда work land
        перепроверяет доказательство по хэшу дерева работы и лишь затем пишет
        событие приземления; потребитель — журнал. Схема работает офлайн,
        потому что вердикт уже привязан к дереву, а не к прогону.

        Удалённый CI на каждый push (решение 18): калитка gate и проверка
        сообщений msg-check --range исполняются на GitHub по дереву каждого
        коммита и отказывают плохую вершину master. Исполнение после записи,
        но вердикт тот же контентно-адресуемый, а потребитель — основная ветка.

        Первый набор проверок DACC: на закрытии работы — доказательство и work
        land (решение 15); на пути в master — CI из решения 18. Защита ветки,
        которая предотвращает прямую запись без вердикта, остаётся отдельной
        работой и сюда не входит.
    ",
    trade_offs: &[
        "Плюс: CiGate определён свойством вердикта и потребителя, а не тем, где исполнен прогон",
        "Плюс: закрытие работы проверяется офлайн — удалённый CI не обязателен для контентно-адресуемого вердикта",
        "Плюс: удалённый CI ловит коммит без основания и правку на сайте на пути в master",
        "Минус: прямая запись в master без защищённой ветки обнаруживается, а не предотвращается",
        "Минус: независимость вердикта не есть правильность кода — честный прогон плохого кода всё равно проходит",
        "Минус: контентная перепроверка стоит повторного прогона калитки на чужой машине",
    ],
    constraints: &[
        "CiGate определяется независимостью вердикта и его потребителя, а не местом исполнения.",
        "Вердикт CiGate контентно-адресуем (решение 15) и перепроверяем с дерева.",
        "Новый разбор чужого вывода заводится только вместе с контролем на смену формата (решение 22).",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 9, 28),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_002],
);
