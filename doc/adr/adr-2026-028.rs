use crate::taxonomy::{channel, Subsystem};
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "gate_command — собственный гейт проекта вместо шагов cargo, а не вдобавок к ним",
    status: DocStatus::Active,
    channel: channel::Public,
    subsystems: &[taxon!(Subsystem, Cli), taxon!(Subsystem, Methodology)],
    context: r"
        Находка пилота: gate_command (например, cargo xtask ci) сам гоняет
        форматирование, clippy и тесты, а калитка DACC повторяет их на шагах
        5–13 — двойной прогон одних и тех же проверок. Решение 20 ввело
        gate_command как делегирование проверки, но как дополнительный шаг, а не
        как замену пересекающихся шагов.
    ",
    decision: r"
        Команда проекта заменяет стандартные шаги cargo, а не добавляется к ним.
        Когда gate_command задана, DACC пропускает шаги, которые делает
        команда проекта: форматирование, clippy, тесты, документацию, сборку на
        минимальной версии и проверку зависимостей (шаги 5–7, 10, 11, 13).

        DACC оставляет себе то, что не делегируется: внешние имена,
        относительные ссылки в markdown, журнал (шаги 1–3) и доказательство
        атак — пробу сверки кодов, атаки и их прогон на минимальной версии под
        RUSTC_BOOTSTRAP (шаги 8, 9, 12). Это ядро обещания «гарантии честны и
        проверены атакой», и его не заменяет никакая команда проекта.

        Двойного прогона нет: каждая проверка принадлежит одному исполнителю.
    ",
    trade_offs: &[
        "Плюс: одна проверка — один исполнитель, двойного прогона нет",
        "Плюс: ядро DACC (атаки, журнал, внешние имена) не делегируется",
        "Минус: проект обязан покрыть своей командой fmt/clippy/test/doc/MSRV/deny — иначе проверка исчезает",
        "Минус: атаки по-прежнему прогоняются отдельно под RUSTC_BOOTSTRAP — ещё один прогон cargo поверх команды проекта",
    ],
    constraints: &[
        "gate_command заменяет шаги 5–7, 10, 11 и 13; шаги 1–3, 8, 9 и 12 остаются за DACC.",
        "Доказательство атак не делегируется никогда.",
        "Без gate_command калитка ведёт все шаги сама.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 9, 28),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_002],
);
