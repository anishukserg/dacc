use crate::taxonomy::{channel, Subsystem};
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "Slug-идентификатор работы",
    status: DocStatus::Active,
    channel: channel::Public,
    subsystems: &[taxon!(Subsystem, Work), taxon!(Subsystem, Scan), taxon!(Subsystem, Cli)],
    context: r"
        Слой работы (Thrust/Slice/WorkItem) адресуется числом: макросы
        thrust!/slice!/work! принимают числовой аргумент, Subject журнала —
        Work(u32)/Slice(u32), трейлеры коммитов — Dacc-Work: wNNNN. Число
        нечитаемо: w0061 не говорит, что это, и отслеживать «где что» трудно.

        ADR-023 перевёл слой знания на slug и оставил слой работы на числах с
        оговоркой: «пересмотр — только вместе с контентно-адресуемой привязкой
        журнала к дереву». Эта привязка уже есть (решение 15): доказательство
        хранится под хэшем дерева без каталога журнала, а не под числом.
        Поэтому оговорка выполнена, и пересмотр возможен.
    ",
    decision: r"
        Идентификатор слоя работы — slug из имени файла; единственный источник
        идентичности — имя файла, как у слоя знания (ADR-023). Макросы
        thrust!/slice!/work! числового аргумента не имеют, поле id из записей
        работы удалено: запись не нумерует себя, реестр адресует её по имени
        файла. Алфавит slug — общее правило check_slug_id: строчные латинские,
        цифры, дефис, с буквы, без подчёркивания и ключевых слов. Префикс
        класса t-/s-/w- остаётся частью slug, чтобы отличать направления,
        срезы и работы.

        Ссылочные типы ThrustRef/SliceRef/WorkRef переходят с u32 на
        slug-строку (по образцу AdrRef/RfcRef); Subject журнала —
        Work(Slug)/Slice(Slug); трейлеры — Dacc-Work: <slug> и
        Dacc-Slice: <slug>. Доказательство готовности не меняется: оно уже
        контентно-адресуемо (решение 15).
    ",
    trade_offs: &[
        "Плюс: идентификатор читаем и определяется именем файла, а не глобальным счётчиком",
        "Плюс: единственный источник идентичности — имя файла; расхождение «макрос vs имя» невыразимо",
        "Плюс: правило slug переиспользует механизм якорей и слоя знания — один код на всех",
        "Минус: разовая миграция 65 работ, 23 срезов, 4 направлений и их журнала",
        "Минус: прошлая история git с трейлерами Dacc-Work: wNNNN остаётся как есть",
    ],
    constraints: &[
        "Идентификатор слоя работы — имя файла; числового аргумента в макросах thrust!/slice!/work! нет.",
        "Slug подчиняется общему правилу check_slug_id и несёт префикс класса t-/s-/w-.",
        "Доказательство готовности остаётся контентно-адресуемым (решение 15) и не меняется.",
        "Журнал и трейлеры ссылаются на slug, а не на число.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 9, 28),
    breaking: Breaking::Yes {
        migration: nonempty_str![
            "Переименовать файлы thrust/, slice/, work/ в slug-имена.",
            "Убрать числовой аргумент из вызовов thrust!/slice!/work!.",
            "Заменить ThrustRef/SliceRef/WorkRef и Subject с u32 на slug.",
            "Обновить журнал, трейлеры и команды cargo dacc work/slice.",
        ],
    },
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_002],
);
