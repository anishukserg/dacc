use crate::taxonomy::{channel, Subsystem};
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "Текст инструмента — английский: вывод, создаваемые коммиты, порождённые файлы",
    status: DocStatus::SupersededBy(crate::adr::adr_2026_022),
    channel: channel::Public,
    subsystems: &[taxon!(Subsystem, Cli)],
    context: r"
        Инструмент печатает и записывает русский текст в репозиторий продукта:
        пять тем служебных коммитов журнала, вердикт калитки внутрь поля
        события, комментарий в порождённом хуке. Текст отказа сверх того
        ссылается на doc/adr/a0008.rs — номер решения чужого реестра, где под
        этим номером другое решение или ничего. Внедрение в англоязычный
        проект дало русские темы в его истории.

        Рассматривались: два языка встроенными таблицами — новый язык требует
        выпуска DACC; каталог сообщений отдельным файлом — формат, правило
        для пропущенных строк и расхождение переводов с кодом; только
        английский.
    ",
    decision: r"
        Весь текст инструмента — английский: вывод в консоль, темы и тела
        коммитов, которые он создаёт, комментарии порождённых хуков. Настройки
        языка нет.

        Документы методологии остаются русскими: это тексты DACC, а не
        вывод инструмента.

        Поле вердикта в событии журнала остаётся прозой: с английским выводом
        язык уходит из данных сам, и формат события менять не нужно. Прежние
        события с русским вердиктом не переписываются — файл события неизменен
        (решение 15).

        Ссылку на правила коммитов инструмент берёт из настройки продукта
        (решение 20); без настройки отказ не называет чужой документ.

        Служебные темы коммитов журнала продукт задаёт шаблонами в настройке:
        в русскоязычном проекте они остаются русскими, и это его выбор, а не
        язык инструмента.
    ",
    trade_offs: &[
        "Плюс: один язык — ни каталогов, ни настройки языка, ни расхождения перевода с кодом",
        "Плюс: разбор вывода машиной не зависит от локали",
        "Плюс: инструмент не называет в отказе документ чужого реестра",
        "Минус: DACC ведёт документы по-русски, а его инструмент отвечает по-английски",
        "Минус: русскоязычной команде сообщения об ошибках понятны хуже",
        "Минус: перевод строк меняет тексты, на которые опираются сценарии и документы",
    ],
    constraints: &[
        "Новая строка вывода пишется по-английски.",
        "Документы методологии остаются русскими.",
        "Прежние события журнала с русским вердиктом не переписываются.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 9, 18),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_002],
);
