use crate::taxonomy::{channel, Subsystem};
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "Ратчет миграции: baseline известного долга, блокируются только новые нарушения",
    status: DocStatus::Active,
    channel: channel::Public,
    subsystems: &[taxon!(Subsystem, Scan), taxon!(Subsystem, Methodology)],
    context: r"
        Введение новой строгой проверки на реестр с уже накопленным долгом
        упирается в дилемму: чинить весь долг разом — дорого и блокирует саму
        миграцию, не вводить проверку — долг продолжает расти молча. Нужен
        механизм, который замораживает известный долг и блокирует только новые
        нарушения: проверка вводится сразу, а долг не растёт.

        Без такого механизма строгая проверка либо откладывается «до починки
        всего», либо вводится с исключениями, которые никто не видит. Первое —
        вечная отсрочка, второе — молчаливый обход, неотличимый от небрежности.
    ",
    decision: r"
        Вводится ратчет миграции: declare_baseline! объявляет baseline — список
        известных нарушений, замороженный и названный по имени. Скан сверяет
        текущие нарушения с baseline: нарушение из baseline разрешено и названо,
        нарушение вне baseline — ошибка сборки.

        Baseline только уменьшается, и только отдельным решением: починенное
        нарушение убирается из baseline явно, а не молча. Добавление нарушения в
        baseline — тоже отдельное решение, иначе baseline стал бы легализацией
        нового долга.

        Механизм — надстройка над сканом: проверка объявляет baseline, скан
        вычисляет текущее число нарушений и сравнивает с ним. Нарушение роста —
        ошибка сборки, а не находка ревью.
    ",
    trade_offs: &[
        "Плюс: строгая проверка вводится сразу, долг не растёт с первого коммита",
        "Плюс: известный долг назван в baseline, а не молчалив",
        "Плюс: нарушение роста — ошибка сборки, а не находка ревью",
        "Минус: baseline — список, который надо вести; забытое нарушение остаётся навсегда",
        "Минус: ратчет блокирует только рост и сам по себе не заставляет чинить baseline",
    ],
    constraints: &[
        "Новое нарушение вне baseline — ошибка сборки.",
        "Починенное нарушение убирается из baseline отдельным решением, а не молча.",
        "Добавление нарушения в baseline — отдельное решение; baseline не растёт сам.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 9, 29),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_001],
);
