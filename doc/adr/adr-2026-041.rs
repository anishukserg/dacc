use crate::taxonomy::{channel, Subsystem};
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "Гарантия с силой «компилятор» — типизированная запись: обещание, атака и контроль",
    status: DocStatus::Active,
    channel: channel::Public,
    subsystems: &[taxon!(Subsystem, Knowledge), taxon!(Subsystem, Scan)],
    context: r"
        GUARANTEES.md обещает гарантии, но сила «компилятор» держится только
        атакующими compile_fail-тестами, которые никто не связывает с обещанием.
        Обещание без атаки — проза, которую компилятор не видит; атака без
        обещания — тест, смысл которого неизвестен. Пока связь держится
        соглашением, висячее обещание и осиротевшая атака неотличимы от честной
        пары.

        Нужно выразить связь «обещание → атака → позитивный контроль» типом,
        чтобы висячая ссылка на атаку не компилировалась — как ссылка решения на
        размеченный фрагмент кода.
    ",
    decision: r"
        Вводится guarantee! — запись реестра гарантий: обещание (текст), ссылка
        на атакующий compile_fail-тест и ссылка на позитивный контроль. Ссылки —
        пути к константам, порождённым сканом, поэтому гарантия без существующей
        атаки или без контроля не компилируется.

        Реестр гарантий — отдельный каталог guarantee/, по одной записи на файл.
        Скан порождает константу-ссылку на каждую атаку и контроль; опечатка
        или удаление атаки ломает ссылку гарантии обычной ошибкой компилятора.

        Атакующий тест и его контроль помечаются разметкой, как фрагменты кода:
        гарантия ссылается на разметку, а не на номер или имя файла. Это тот же
        приём, что у code-anchors (решение 1), перенесённый на атаки.
    ",
    trade_offs: &[
        "Плюс: висячая гарантия не компилируется — обещание без атаки невыразимо",
        "Плюс: атака и контроль — ссылки, а не свободный текст, опечатка ломает сборку",
        "Плюс: реестр гарантий читается проекцией, как решения и спецификации",
        "Минус: атаки обязаны быть размечены — гарантия без разметки невыразима",
        "Минус: ещё одна ось реестра и ещё один каталог",
    ],
    constraints: &[
        "Гарантия ссылается на атаку и контроль путём; висячая ссылка не компилируется.",
        "Атака и контроль размечены, как фрагменты кода.",
        "Реестр гарантий — отдельный каталог guarantee/, по записи на файл.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 9, 29),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_001],
);
