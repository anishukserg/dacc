use crate::taxonomy::Subsystem;
use slipway_core::{nonempty_str, taxon};
use slipway_knowledge::{Breaking, DocStatus};

slipway_knowledge::adr!(
    title: "Раскладка реестра — библиотечная точка входа, а не копируемый шаблон",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Scan), taxon!(Subsystem, Cli)],
    context: r"
        Новый потребитель получает крейт документов, чей build.rs сегодня — это
        полсотни строк оркестровки: скан решений, спецификаций, плана и журнала,
        порождение и запись файлов. При копировании руками эта оркестровка
        расходится у двух проектов, и исправление в Slipway не доезжает до
        потребителя — второй источник истины.
    ",
    decision: r"
        Оркестровка выносится в библиотечную точку входа slipway-scan: одна
        функция emit_registry(каталог_реестра, OUT_DIR) делает скан, порождение
        и запись всех файлов. build.rs потребителя сводится к вызову этой
        функции, поэтому расходиться нечему: правка Slipway доезжает обновлением
        зависимости.

        Первичная раскладка (Cargo.toml, lib.rs, taxonomy.rs) остаётся
        минимальным шаблоном, который порождает команда slipway init; без неё —
        рукописный минимум из нескольких строк. Цена смены API скана для уже
        порождённого: у потребителя меняется только сигнатура точки входа,
        порождённые файлы пересобираются.
    ",
    trade_offs: &[
        "Плюс: один источник оркестровки — расхождение раскладки невыразимо",
        "Плюс: потребительский build.rs тривиален и обновляется вместе с крейтом",
        "Минус: точка входа фиксирует форму реестра — её смена ломает старые потребители",
        "Минус: генератор slipway init — отдельная команда сверх точки входа",
    ],
    constraints: &[
        "Оркестровка — одна функция в slipway-scan; потребитель её не копирует.",
        "Порождённые файлы пишутся только в OUT_DIR.",
        "Смена сигнатуры точки входа — ломающее изменение с миграцией.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 28),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_001, crate::rfc::rfc_2026_003],
);
