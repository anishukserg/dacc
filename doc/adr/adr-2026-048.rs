use crate::taxonomy::{channel, Subsystem};
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "Сверка версии инструмента с деревом",
    status: DocStatus::Active,
    channel: channel::Public,
    subsystems: &[taxon!(Subsystem, Cli), taxon!(Subsystem, Methodology)],
    context: r"
        Установленный бинарник cargo-dacc расходится с деревом реестра молча:
        находка v-quality-of-done зафиксировала бинарник 0.3.0 против дерева
        0.4.0 — директивы AGENTS.md отвечали unknown command, состояние работ
        врало. Пилот nerpa назвал тот же класс W-031: локальный инструмент
        писал журнал doc/journal.toml, а реестр дерева сворачивал doc/journal/.
        Оба случая — не опечатка, а штатная установка: версия инструмента и
        версия реестра живут в разных местах, и расхождение обнаруживается
        только повреждением журнала.
    ",
    decision: r"
        Инструмент сверяет свою версию с версией дерева и отказывает работать
        вразнос.

        Мера дерева — версия dacc-work в Cargo.lock реестра: она объявляет
        схему записей и журнала, которую сворачивает build.rs. Версия бинарника —
        его CARGO_PKG_VERSION. Любое расхождение в обе стороны — отказ
        мутирующих команд и калитки с кодом причины tool-version-drift и текстом,
        называющим обе версии и шаг: переустановить инструмент или обновить
        реестр.

        Проверка живёт в одной точке чтения настройки — до разбора аргументов и
        до записи события. Дерево без Cargo.lock проверку не проходит и не
        отказывает: для нерастущего проекта меры нет, и это граница названа, а
        не заполнена выдумкой. Проверка не распространяется на read-only команды
        слоя доступа: карта места не ломает.
    ",
    trade_offs: &[
        "Плюс: расхождение инструмента и дерева ловится до первого события, а не повреждением журнала",
        "Плюс: отказ называет обе версии и шаг — диагноз не требуется",
        "Минус: публикация новой версии требует обновления Cargo.lock потребителя — но это и есть тот шаг, который раньше пропускался",
        "Минус: деревья без Cargo.lock остаются без сверки — граница заявлена",
    ],
    constraints: &[
        "Мера дерева — версия dacc-work в Cargo.lock реестра; версия бинарника — CARGO_PKG_VERSION.",
        "Расхождение в обе стороны — отказ мутирующих команд и калитки с кодом tool-version-drift.",
        "Отказ называет обе версии и шаг исправления.",
        "Дерево без Cargo.lock — сверки нет; read-only команды слоя доступа не отказывают.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 10, 2),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_002],
);
