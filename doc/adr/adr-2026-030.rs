use crate::taxonomy::{channel, Subsystem};
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "Версионирование и выпуск — общая версия workspace, semver, теги vX.Y.Z",
    status: DocStatus::Active,
    channel: channel::Public,
    subsystems: &[taxon!(Subsystem, Methodology), taxon!(Subsystem, Knowledge)],
    context: r"
        Крейты DACC опубликованы в crates.io версией 0.1.0 (решение 25), но в
        репозитории нет ни git-тегов, ни политики поднятия версии. Правки
        калитки (работы 61 и 62) изменили dacc-cli, а на crates.io он остался
        0.1.0 со старым кодом: версия не привязана ни к какому коммиту, и
        неясно, когда и как её поднимать, чтобы crates.io и github совпадали.
    ",
    decision: r"
        Крейты версионируются одной версией рабочего пространства: все
        публикуемые dacc-* делят её и выпускаются вместе (решение 25). Версия
        следует semver для 0.x — patch (0.1.1) за исправления и рефакторинг,
        minor (0.2.0) за новые возможности; major в 0.x не применяется.

        Каждый выпуск — тег vX.Y.Z на коммите с поднятой версией: тег и есть
        соответствие «crates.io ↔ github». Порядок выпуска: поднять версию в
        Cargo.toml, собрать и проверить калиткой, поставить тег vX.Y.Z,
        опубликовать крейты в порядке зависимостей (решение 25), сверить
        cargo search.
    ",
    trade_offs: &[
        "Плюс: версия на crates.io всегда привязана к коммиту тегом.",
        "Плюс: один bump — один выпуск, предсказуемо для потребителя.",
        "Минус: bump общей версии переиздаёт и неизменённые крейты.",
        "Минус: тег не отменяется после публикации, как и сама версия.",
    ],
    constraints: &[
        "Единая версия рабочего пространства: публикуемые крейты делят её и bump вместе.",
        "Тег vX.Y.Z ставится на коммит с поднятой версией; выпуск без тега не считается выпуском.",
        "patch за FIX/REFACTOR, minor за FEAT; major в 0.x не применяется.",
        "Опубликованная версия неизменяема и не переиздаётся (решение 25).",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 9, 28),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_001],
);
