use crate::taxonomy::{channel, Subsystem};
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "Обоснованное отклонение",
    status: DocStatus::Active,
    channel: channel::Public,
    subsystems: &[taxon!(Subsystem, Knowledge), taxon!(Subsystem, Scan)],
    context: r"
        Правило в DACC держится формой записи (решение 4): типом, макросом,
        скан-проверкой или шагом калитки. Там, где нарушение можно сделать
        невыразимым, оно невыразимо.

        Но не всякое правило выразимо типом. Часть правил держится проверкой
        или соглашением, и от них отклоняются осознанно: глушится lint через
        #[allow], не ставится шаг калитки, пишется обход. Сегодня такое
        отклонение молчаливо: реестр собирается, калитка проходит, а причина и
        владелец отклонения нигде не записаны.

        Молчаливое отклонение неотличимо от небрежности: через год нельзя
        понять, было ли #[allow] решением или забывчивостью, и кто за это
        отвечает. У AngaraBase отклонение от контракта допустимо только
        обоснованно: причина обязательна.
    ",
    decision: r"
        Обоснованное отклонение — отдельная запись реестра deviation! с полями:
        правило (ссылка на правило, от которого отклоняются), причина
        (обязательная) и владелец (обязательный).

        Причина и владелец обязательны по типу: запись без причины или без
        владельца не компилируется — невыразимо «отклонение потому что» и
        «отклонение без ответственного».

        Молчаливое отклонение невыразимо: скан находит call-site отклонения
        (например, глушение lint) и требует объявления каждого в реестре;
        необъявленное отклонение — ошибка сборки.

        Отклонение живёт своим циклом: оно либо снято возвратом к правилу,
        либо переклассифицировано — правило изменилось, и отклонение становится
        решением или обязательством. Отклонение без исхода всплывает на разборе,
        как обязательство.
    ",
    trade_offs: &[
        "Плюс: молчаливое отклонение невыразимо — причина и владелец обязательны по типу",
        "Плюс: отклонение — запись реестра, его видит скан и проекция, а не только автор",
        "Минус: ещё одна ось реестра и ещё одна проверка скана",
        "Минус: скан находит call-site отклонения эвристически — отсутствие проверки как форму обхода типом не поймать, это остаётся ревью",
    ],
    constraints: &[
        "Отклонение — отдельная запись deviation!, а не поле существующей записи и не проза.",
        "Причина и владелец обязательны: запись без них не компилируется.",
        "Необъявленное отклонение — ошибка сборки.",
        "Отклонение без исхода всплывает на разборе.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 9, 29),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_001],
);
