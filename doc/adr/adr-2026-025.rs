use crate::taxonomy::Subsystem;
use slipway_core::{nonempty_str, taxon};
use slipway_knowledge::{Breaking, DocStatus};

slipway_knowledge::adr!(
    title: "Доставка крейтов Slipway в сторонний проект — публикация в crates.io",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Methodology), taxon!(Subsystem, Knowledge)],
    context: r"
        Пилот уровня знания на стороннем проекте требует, чтобы крейты Slipway
        попали в проект, чья политика зависимостей допускает только crates.io:
        deny.toml запрещает неизвестные реестры и git-источники. Крейты Slipway
        сегодня — path-зависимости рабочего пространства, в crates.io не
        опубликованы.

        Способов три. Публикация в crates.io: политика соблюдена без исключений.
        Git-зависимость с исключением в политике проекта: быстро, но требует
        правки чужой политики и отступает от её правила. Копия в дереве проекта:
        просто, но обновления ручные, и у потребителя возникает второй источник
        истины — ровно та болезнь, от которой методология лечит.
    ",
    decision: r"
        Крейты доставляются публикацией в crates.io. Они уже подготовлены к
        этому: версия 0.1.0, лицензия Apache-2.0, адрес репозитория и
        rust-version 1.83 объявлены в манифестах (решение 13). Пилот потребляет
        их обычными зависимостями, закреплёнными по версии.

        Публикуются вместе, одним выпуском, потому что делят версию рабочего
        пространства. Для L1 публикуются пять крейтов в порядке зависимости:
        slipway-core и slipway-journal (без зависимостей), затем
        slipway-knowledge и slipway-derive (на core), затем slipway-scan (на
        core и journal). slipway-journal попадает транзитивно — скан реестра
        лежит одним крейтом со знанием, планом и журналом. Документы и примеры
        остаются непубликуемыми.

        Цена: каждое нужное пилоту изменение — новый выпуск, а не мгновенная
        path-зависимость. Необратимое: опубликованная версия неизменяема, yank
        не возвращает имя; 0.x допускает ломающие изменения, но не отзывает уже
        скачанные.
    ",
    trade_offs: &[
        "Плюс: политика crates.io-only соблюдена без исключений в чужом проекте",
        "Плюс: закрепление по версии даёт воспроизводимую сборку реестра пилота",
        "Минус: обратная связь медленнее path-зависимости — каждый фикс требует выпуска",
        "Минус: публикация черновика 0.x — публичное обязательство с неизменяемыми версиями",
    ],
    constraints: &[
        "Публикуются пять крейтов L1 — core, journal, knowledge, derive, scan; doc/ и examples/ не публикуются.",
        "MSRV 1.83 держится у опубликованных крейтов.",
        "Выпуск публикует пять крейтов в порядке зависимости — они делят версию рабочего пространства.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: slipway_core::date!(2026, 9, 28),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_001],
);
