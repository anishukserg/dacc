use crate::taxonomy::{channel, Subsystem};
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "Контрактная граница",
    status: DocStatus::Active,
    channel: channel::Public,
    subsystems: &[taxon!(Subsystem, Methodology), taxon!(Subsystem, Scan)],
    context: r"
        Крейты DACC образуют направленный граф: dacc-core внизу, над ним знание,
        работа и журнал, выше скан и доступ, на вершине инструмент и фасад.
        Направление заявлено в DACC.md, но не держится механизмом: крейт может
        импортировать «вверх» (dacc-core → dacc-knowledge), и сборка это
        пропустит — обратная зависимость или цикл ловится только ревью.

        Часть типов обязана быть закрыта для внешней реализации: ссылочные
        типы (AdrRef, WorkRef, Channel, Taxon) конструируются только сканом или
        макросом объявления, а не пользовательским кодом. Сегодня это держится
        соглашением и проверкой скана по имени конструктора, а не типом.

        declare_channels! объявляет закрытый набор значений путём к константе;
        границы нуждаются в том же: объявить направление зависимости и
        закрытость реализации так, чтобы нарушение не собиралось, а не
        вылавливалось grep'ом по имени.
    ",
    decision: r"
        Направление зависимости объявляется графом допустимых рёбер: продукт
        объявляет, какой крейт от какого зависит (declare_boundary!). Скан читает
        манифесты Cargo.toml рабочего пространства и сверяет фактический граф
        зависимостей с объявленным. Необъявленное ребро — импорт «вверх», цикл
        или новая зависимость без объявления — ошибка сборки, а не находка
        ревью.

        Sealed-реализация выражается sealed-трейтом: публичный трейт с
        приватным супертрейтом, который могут назвать только крейты-владельцы.
        Реализация типа извне невыразима типом. Конструкторы скана
        (__from_scan, __new_unchecked) перестают быть полем проверки по имени и
        становятся видимостью: вызывать их может только порождённый код.

        Оба механизма — надстройка над уже существующим объявлением закрытых
        наборов (declare_channels!, declare_taxonomy!): объявление живёт в
        реестре, нарушение держится формой записи или сборкой, а не проверкой.
    ",
    trade_offs: &[
        "Плюс: направление зависимостей держится сборкой, а не диаграммой в прозе",
        "Плюс: sealed-реализация закрыта типом — внешняя реализация невыразима, а не запрещена проверкой",
        "Плюс: объявление границы — реестр, его видит скан и проекция",
        "Минус: граф зависимостей читается из Cargo.toml, а не из типов — расхождение объявления и манифеста ловит скан, а не компилятор",
        "Минус: sealed-трейт добавляет приватный супертрейт на каждый закрытый тип",
    ],
    constraints: &[
        "Направление зависимости объявляется графом рёбер; необъявленное ребро — ошибка сборки.",
        "Закрытый тип реализуется только крейтами-владельцами; внешняя реализация невыразима.",
        "Конструкторы скана вызываются только порождённым кодом.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 9, 29),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_001, crate::rfc::rfc_2026_002],
);
