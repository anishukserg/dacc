use crate::taxonomy::Subsystem;
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "Документы реестра лежат в корне крейта, без каталога src",
    status: DocStatus::Active,
    subsystems: &[taxon!(Subsystem, Knowledge), taxon!(Subsystem, Work)],
    context: r"
        Реестр — прежде всего документы, которые читает человек. Путь
        crates/dacc-meta/src/adr/a0001.rs давал пять уровней до решения,
        и уровень src ничего не сообщал: это умолчание Cargo для библиотек,
        а не смысл.

        Рассматривались три раскладки: убрать src только у крейтов реестров;
        вынести реестры в корень репозитория; убрать src у всех крейтов.
    ",
    decision: r#"
        У крейтов реестров — решений и спецификаций, плана, демо-реестра —
        корень библиотеки задан в манифесте (`[lib] path = "lib.rs"`), а
        каталоги документов лежат рядом с манифестом: adr/, rfc/, thrust/,
        slice/, work/. Библиотеки методологии сохраняют src/ по соглашению
        экосистемы.

        Эта же раскладка предлагается продуктам для их реестров.
    "#,
    trade_offs: &[
        "Плюс: до документа четыре уровня вместо пяти, и каждый что-то значит",
        "Плюс: библиотеки выглядят так, как ожидает читатель экосистемы Rust",
        "Минус: в одном репозитории две раскладки — реестры без src, библиотеки с src",
        "Минус: путь к корню библиотеки задаётся в манифесте каждого крейта реестра вручную",
    ],
    constraints: &[
        "Каталоги документов реестра не вкладываются в src.",
        "Скрипт, читающий реестр по путям, держит эти пути в одном месте в своём начале.",
    ],
    authors: nonempty_str!["Анищук Сергей"],
    decided_at: dacc_core::date!(2026, 9, 10),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_001, crate::rfc::rfc_2026_002],
);
